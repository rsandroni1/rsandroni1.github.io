// Day-stable pick: returns the same quote for a given dateIso across reloads.
export function quoteFor(dateIso) {
  if (!dateIso) return QUOTES[0];
  // simple deterministic hash from the date string
  let h = 0;
  for (let i = 0; i < dateIso.length; i++) h = ((h << 5) - h + dateIso.charCodeAt(i)) | 0;
  const idx = Math.abs(h) % QUOTES.length;
  return QUOTES[idx];
}

// Truly random — used for "show me another" tap
export function randomQuote(excludeIdx = -1) {
  let idx;
  do { idx = Math.floor(Math.random() * QUOTES.length); }
  while (idx === excludeIdx && QUOTES.length > 1);
  return { ...QUOTES[idx], idx };
}
